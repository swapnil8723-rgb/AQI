/**
 * UI strings, English and Hindi. English at the root, Hindi under /hi/
 * (PLAN.md §4). Digits stay Latin in both (DESIGN.md §3). The word
 * "Official" / "आधिकारिक" is used ONLY for the CPCB bulletin value.
 */

export type Lang = 'en' | 'hi';
export const LANGS: Lang[] = ['en', 'hi'];

export function localePath(lang: Lang, path: string): string {
  if (lang === 'en') return path;
  return path === '/' ? '/hi' : `/hi${path}`;
}

/** Strip the /hi prefix to get the language-neutral path. */
export function basePath(pathname: string): string {
  if (pathname === '/hi' || pathname === '/hi/') return '/';
  return pathname.startsWith('/hi/') ? pathname.slice(3) : pathname;
}

